import {readFile,writeFile} from 'node:fs/promises';
const files=['supabase.sql','supabase-pr2.sql','supabase-security.sql'];
const parts=await Promise.all(files.map(file=>readFile(new URL(`../${file}`,import.meta.url),'utf8')));
// A single outer transaction makes a failed install leave existing data intact.
parts[2]=parts[2].replace(/^begin;\s*$/m,'').replace(/^commit;\s*$/m,'');
const output='-- Generated by npm run build:database. Do not edit this file directly.\n'+
  '-- Run this WHOLE file in the Supabase SQL Editor for a new or incomplete setup.\n'+
  '-- Existing app rows are retained; all security fixes are applied last.\n\nbegin;\n\n'+
  parts.map((part,i)=>`-- ===== ${files[i]} =====\n${part.trim()}\n`).join('\n')+
  "\nnotify pgrst, 'reload schema';\ncommit;\n";
const target=new URL('../supabase-install.sql',import.meta.url);
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==output) throw new Error('supabase-install.sql is stale; run npm run build:database');
} else await writeFile(target,output);

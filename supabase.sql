create or replace function public.has_staff_access(check_user uuid default auth.uid(), required text default 'moderator')
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from profiles p where p.id=check_user and (
    'OWNER'=any(p.tags) or
    (required<>'owner' and 'CO-OWNER'=any(p.tags)) or
    (required='moderator' and ('MOD'=any(p.tags) or p.role='moderator'))
  ));
$$;
grant execute on function public.has_staff_access(uuid,text) to authenticated;

create or replace function public.is_moderator(check_user uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public as $$
  select public.has_staff_access(check_user,'moderator');
$$;

create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if (new.role is distinct from old.role or new.tags is distinct from old.tags)
     and not public.has_staff_access(auth.uid(),'owner') then
    raise exception 'Only an owner can change account tags or staff access';
  end if;
  return new;
end;$$;

create or replace function public.enforce_message_access()
returns trigger language plpgsql security definer set search_path=public as $$
declare r rooms%rowtype; last_at timestamptz;
begin
  select * into r from rooms where slug=new.room;
  if not found then raise exception 'Room does not exist'; end if;
  if r.minimum_role<>'everyone' and not public.has_staff_access(new.user_id,r.minimum_role) then raise exception 'This room is locked to %+',r.minimum_role; end if;
  if exists(select 1 from moderation_actions a where a.target_user_id=new.user_id and a.revoked_at is null and (a.expires_at is null or a.expires_at>now()) and a.action_type in ('timeout','mute','kick','ban') and (a.room_slug is null or a.room_slug=new.room)) then raise exception 'You cannot post while a moderation action is active'; end if;
  if r.media_mode='images_only' and new.body !~* '^https?://[^[:space:]]+$' then raise exception '#% accepts image/GIF links only',new.room; end if;
  if r.media_mode='disabled' and new.body ~* '^https?://[^[:space:]]+$' then raise exception 'Media is disabled in this room'; end if;
  if not public.has_staff_access(new.user_id,'moderator') and r.slow_mode_seconds>0 then
    select max(created_at) into last_at from messages where user_id=new.user_id and room=new.room;
    if last_at is not null and now()<last_at+make_interval(secs=>r.slow_mode_seconds) then raise exception 'Slow mode: wait % seconds',ceil(extract(epoch from(last_at+make_interval(secs=>r.slow_mode_seconds)-now()))); end if;
  end if;
  return new;
end;$$;
drop trigger if exists enforce_lobby_slow_mode_trigger on public.messages;
drop trigger if exists enforce_media_only_rooms_trigger on public.messages;
drop trigger if exists enforce_message_access_trigger on public.messages;
create trigger enforce_message_access_trigger before insert on public.messages for each row execute function public.enforce_message_access();

create or replace function public.protect_room_staff_fields()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if not public.is_moderator(auth.uid()) and (new.owner_id is distinct from old.owner_id or new.minimum_role is distinct from old.minimum_role or new.is_builtin is distinct from old.is_builtin) then raise exception 'Only staff can change room ownership or access locks'; end if;
  return new;
end;$$;
drop trigger if exists protect_room_staff_fields_trigger on public.rooms;
create trigger protect_room_staff_fields_trigger before update on public.rooms for each row execute function public.protect_room_staff_fields();


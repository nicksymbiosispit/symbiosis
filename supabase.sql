-- Role checks run through a security-definer helper to avoid recursive profile RLS.
create or replace function public.is_moderator(check_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = check_user and role = 'moderator'
  );
$$;

revoke all on function public.is_moderator(uuid) from public;
grant execute on function public.is_moderator(uuid) to authenticated;

-- This helper can see both sides of a block while keeping the block list private.
create or replace function public.users_blocked(user_a uuid, user_b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.blocks
    where (blocker_id = user_a and blocked_id = user_b)
       or (blocker_id = user_b and blocked_id = user_a)
  );
$$;

revoke all on function public.users_blocked(uuid, uuid) from public;
grant execute on function public.users_blocked(uuid, uuid) to authenticated;

-- The UI asks this after every reload/view change. It uses database time and
-- message history, so navigating away cannot reset the visible cooldown.
drop function if exists public.my_lobby_cooldown_remaining();
create or replace function public.my_lobby_cooldown_remaining(check_room text default 'lobby')
returns integer
language sql
stable
security definer
set search_path = public
as $$
  with timing as (
    select
      (select max(created_at) from public.messages where user_id = auth.uid() and room = check_room) as last_at,
      coalesce((select slow_mode_seconds from public.lobby_settings where id = 1), 0) as seconds
  )
  select case
    when public.is_moderator(auth.uid()) or last_at is null or seconds = 0 then 0
    else greatest(0, ceil(extract(epoch from (last_at + make_interval(secs => seconds) - now())))::integer)
  end
  from timing;
$$;

revoke all on function public.my_lobby_cooldown_remaining(text) from public;
grant execute on function public.my_lobby_cooldown_remaining(text) to authenticated;

-- Normal users can edit their profile, but cannot promote themselves.
create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role is distinct from old.role
     and auth.uid() is not null
     and not public.is_moderator(auth.uid()) then
    raise exception 'Only moderators can change account roles';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role_trigger on public.profiles;
create trigger protect_profile_role_trigger
before update on public.profiles
for each row execute function public.protect_profile_role();

-- Enforce lobby slow mode in the database so it cannot be bypassed in DevTools.
create or replace function public.enforce_lobby_slow_mode()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  wait_seconds integer;
  last_message_at timestamptz;
  remaining integer;
begin
  if public.is_moderator(new.user_id) then
    return new;
  end if;

  select slow_mode_seconds into wait_seconds
  from public.lobby_settings where id = 1;

  if coalesce(wait_seconds, 0) = 0 then
    return new;
  end if;

  select max(created_at) into last_message_at
  from public.messages where user_id = new.user_id and room = new.room;

  if last_message_at is not null and now() < last_message_at + make_interval(secs => wait_seconds) then
    remaining := ceil(extract(epoch from ((last_message_at + make_interval(secs => wait_seconds)) - now())))::integer;
    raise exception 'Slow mode is active. Wait % second(s).', greatest(remaining, 1);
  end if;

  return new;
end;
$$;

drop trigger if exists enforce_lobby_slow_mode_trigger on public.messages;
create trigger enforce_lobby_slow_mode_trigger
before insert on public.messages
for each row execute function public.enforce_lobby_slow_mode();

-- Random and nostalgia are media boards. They accept uploads, direct media URLs,
-- and share-page URLs from services such as Tenor and Giphy.
create or replace function public.enforce_media_only_rooms()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.room in ('random','nostalgia') and new.body !~* '^https?://[^[:space:]]+$' then
    raise exception '#% accepts media links only', new.room;
  end if;
  return new;
end;
$$;

drop trigger if exists enforce_media_only_rooms_trigger on public.messages;
create trigger enforce_media_only_rooms_trigger
before insert on public.messages
for each row execute function public.enforce_media_only_rooms();

